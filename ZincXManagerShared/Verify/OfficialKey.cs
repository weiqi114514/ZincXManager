    /// <summary>造一把只能验签的公钥(RSA 验签在 AOT 下走系统 CNG,不需要额外依赖)。</summary>
    public static RSA? Create()
    {
        try
        {
            if (Vault.Length != 256 || Seed.Length != 32)
            {
                return null;
            }

            var stream = Keystream(Vault.Length);
            var modulus = new byte[Vault.Length];
            for (var i = 0; i < modulus.Length; i++)
            {
                modulus[i] = (byte)(Vault[i] ^ stream[i]);
            }

            var rsa = RSA.Create();
            rsa.ImportParameters(new RSAParameters
            {
                Modulus = modulus,
                Exponent = [0x01, 0x00, 0x01],   // 65537
            });

            return rsa;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>链式 SHA-256 铺开的密钥流(和 Seed 一起由签发工具生成)。</summary>
    private static byte[] Keystream(int length)
    {
        var output = new byte[length];
        var block = Seed;
        var offset = 0;

        while (offset < length)
        {
            block = SHA256.HashData(block);
            var take = Math.Min(block.Length, length - offset);
            Array.Copy(block, 0, output, offset, take);
            offset += take;
        }

        return output;
    }
